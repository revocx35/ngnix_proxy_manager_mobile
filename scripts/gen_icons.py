#!/usr/bin/env python3
"""Regenerates app/src/main/java/.../ui/theme/AppIcons.kt from Google's Material Symbols SVGs.

Add an entry to ICONS (Kotlin name -> Material Symbols name, see https://fonts.google.com/icons) and run:
    python3 scripts/gen_icons.py
"""
import os
import re
import urllib.request

ICONS = {
    'Dashboard': 'space_dashboard', 'Hosts': 'dns', 'Redirect': 'turn_right', 'Stream': 'cable', 'Dead': 'block',
    'Certificate': 'verified_user', 'AccessList': 'shield_lock', 'Users': 'group', 'History': 'history',
    'Settings': 'settings', 'More': 'more_horiz', 'Add': 'add', 'Edit': 'edit', 'Delete': 'delete',
    'Power': 'power_settings_new', 'Search': 'search', 'Close': 'close', 'Back': 'arrow_back', 'Refresh': 'refresh',
    'Check': 'check', 'CheckCircle': 'check_circle', 'Error': 'error', 'Warning': 'warning', 'Info': 'info',
    'Visibility': 'visibility', 'VisibilityOff': 'visibility_off', 'Logout': 'logout', 'Person': 'person',
    'Key': 'key', 'Lock': 'lock', 'LockOpen': 'lock_open', 'Download': 'download', 'UploadFile': 'upload_file',
    'OpenInNew': 'open_in_new', 'Copy': 'content_copy', 'Public': 'public', 'Schedule': 'schedule',
    'ExpandMore': 'expand_more', 'ExpandLess': 'expand_less', 'MoreVert': 'more_vert', 'Renew': 'autorenew',
    'Forward': 'arrow_forward', 'QrCode': 'qr_code_2', 'Security': 'security', 'Palette': 'palette',
    'Bug': 'bug_report', 'Cloud': 'cloud', 'Route': 'route', 'Code': 'code', 'Language': 'language',
    'AccountCircle': 'account_circle', 'PersonAdd': 'person_add', 'Mail': 'mail', 'Link': 'link',
    'Update': 'update', 'Sync': 'sync', 'Server': 'host', 'Shield': 'shield', 'Help': 'help', 'Pending': 'pending',
    'Web': 'web', 'Tune': 'tune', 'Filter': 'filter_list', 'Admin': 'admin_panel_settings', 'Swap': 'swap_horiz',
    'ChevronRight': 'chevron_right', 'Home': 'home',
}

URL = 'https://fonts.gstatic.com/s/i/short-term/release/materialsymbolsoutlined/{}/default/24px.svg'
OUT = os.path.join(os.path.dirname(__file__), '..', 'app/src/main/java/io/github/revocx35/npmmobile/ui/theme/AppIcons.kt')

lines = [
    'package io.github.revocx35.npmmobile.ui.theme',
    '',
    'import androidx.compose.ui.graphics.Color',
    'import androidx.compose.ui.graphics.SolidColor',
    'import androidx.compose.ui.graphics.vector.ImageVector',
    'import androidx.compose.ui.graphics.vector.addPathNodes',
    'import androidx.compose.ui.unit.dp',
    '',
    '/**',
    ' * Material Symbols (Outlined, weight 400) used by the app. Generated by scripts/gen_icons.py from Google\'s',
    ' * published SVGs (Apache 2.0), so only these icons ship instead of the whole icon library. Do not edit by hand.',
    ' */',
    'object AppIcons {',
]
for name, symbol in ICONS.items():
    svg = urllib.request.urlopen(URL.format(symbol), timeout=30).read().decode()
    paths = re.findall(r' d="([^"]+)"', svg)
    if not paths:
        raise SystemExit(f'no path in {symbol}')
    lines.append(f'    val {name}: ImageVector by lazy {{ icon("{symbol}", "{" ".join(paths)}") }}')
lines += [
    '',
    '    private fun icon(name: String, pathData: String): ImageVector =',
    '        ImageVector.Builder(name, 24.dp, 24.dp, viewportWidth = 960f, viewportHeight = 960f)',
    '            // Material Symbols use viewBox="0 -960 960 960".',
    '            .addGroup(translationY = 960f)',
    '            .addPath(pathData = addPathNodes(pathData), fill = SolidColor(Color.Black))',
    '            .clearGroup()',
    '            .build()',
    '}',
    '',
]
with open(OUT, 'w') as f:
    f.write('\n'.join(lines))
print(f'{len(ICONS)} icons -> {os.path.normpath(OUT)}')
